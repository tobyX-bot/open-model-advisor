export function readStoredLanguage() {
  try {
    const language = localStorage.getItem("oma-language");
    return language === "zh" ? "zh" : "en";
  } catch (error) {
    return "en";
  }
}

export function writeStoredLanguage(language) {
  try {
    localStorage.setItem("oma-language", language);
  } catch (error) {
    // Persistence is optional; blocked storage must not break the advisor.
  }
}

export function translate(language, key, variables = {}) {
  const dictionary = translations[language] || translations.en;
  const value = dictionary[key] || translations.en[key] || key;
  return Object.entries(variables).reduce(
    (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
    value
  );
}

